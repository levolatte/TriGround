"""为两份现有人工验收包生成易读的单题静态页面；原始 HTML 只备份一次。"""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "results"
ACCEPTANCE = RESULTS / "multimodal_data_20260925" / "human_acceptance"
ASSETS = Path(__file__).parent
TRANSLATIONS = RESULTS / "review_ui_20260926" / "query_translations.json"
PACKAGES = ("natural100_seed2026", "correspondence100_seed2026")


def original(path: Path) -> str:
    backup = path.with_name(path.stem + ".original_20260926.html")
    if not backup.exists():
        backup.write_bytes(path.read_bytes())
    return backup.read_text(encoding="utf-8")


def page(package: str, translations: dict[str, str]) -> None:
    path = ACCEPTANCE / package / "review.html"
    source = original(path)
    if package == "correspondence100_seed2026":
        source = source.replace("<img src=", "<img loading=\"lazy\" src=")
    assert source.count("</body>") == 1, path
    css = (ASSETS / "review_ui_20260926.css").read_text(encoding="utf-8")
    js = (ASSETS / "review_ui_20260926.js").read_text(encoding="utf-8")
    payload = json.dumps(translations, ensure_ascii=False).replace("<", "\\u003c")
    injected = (
        "\n<!-- Generated by code/tools/build_review_ui_20260926.py; original HTML preserved alongside. -->\n"
        f"<style id=\"review-ui-20260926-style\">\n{css}\n</style>\n"
        f"<script id=\"review-ui-20260926-script\">\n"
        f"const REVIEW_UI_KIND={json.dumps(package)};\n"
        f"const REVIEW_UI_TRANSLATIONS={payload};\n{js}\n</script>\n"
    )
    path.write_text(source.replace("</body>", injected + "</body>"), encoding="utf-8", newline="\n")


