def main() -> None:
    translations = json.loads(TRANSLATIONS.read_text(encoding="utf-8")) if TRANSLATIONS.exists() else {}
    if not isinstance(translations, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in translations.items()):
        raise ValueError("query_translations.json 必须是英文原文到中文译文的字符串字典")
    for package in PACKAGES:
        page(package, translations)
    entrance()
    print(f"已生成两份 100 条验收页和统一入口；可用译文 {len(translations)} 条。")


if __name__ == "__main__":
    main()
